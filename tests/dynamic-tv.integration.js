import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
import { createApplication } from '../src/server.js';
import { fakeCastDriver } from './cast-fixture.js';

async function until(predicate, description, timeout = 15000) {
  const deadline = Date.now() + timeout;
  while (Date.now() < deadline) {
    if (await predicate()) return;
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  throw new Error(`Timed out: ${description}`);
}

test('add, control, and remove TVs through the dashboard without interrupting other displays', { timeout: 120000 }, async t => {
  const dataDirectory = await mkdtemp(path.join(os.tmpdir(), 'queue-dynamic-browser-'));
  const driver = fakeCastDriver();
  const options = { dataDirectory, browser: { headless: true }, cast: { launch: driver.launch } };
  let app = await createApplication(options);
  const browser = await chromium.launch({ headless: true });
  t.after(async () => { await browser.close(); await app.close(); await rm(dataDirectory, { recursive: true, force: true }); });
  const { port } = await app.listen(0, '127.0.0.1');
  const base = `http://127.0.0.1:${port}`;
  let token = (await (await fetch(`${base}/api/admin/session`)).json()).token;
  const api = async (route, body = {}) => {
    const response = await fetch(`${base}/api/admin/${route}`, { method: 'POST', headers: { 'X-Admin-Token': token, Origin: base, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    const result = await response.json();
    assert.equal(response.status, 200, JSON.stringify(result));
    return result;
  };
  const ui = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const pageErrors = [];
  ui.on('pageerror', error => pageErrors.push(error.message));
  await ui.goto(base);
  await until(async () => await ui.locator('.display-card').count() === 3, 'initial cards');
  await ui.locator('[data-id="1"] summary').click();
  await ui.locator('[data-id="1"] input[name="name"]').fill('Unsaved edit');
  await ui.locator('#add-tv').click();
  await ui.locator('#add-tv-form input[name="name"]').fill('   ');
  await ui.locator('#add-tv-form button[type="submit"]').click();
  await ui.locator('#add-tv-dialog .dialog-error').waitFor({ state: 'visible' });
  assert.equal(app.store.value.devices.length, 3);
  await ui.locator('#add-tv-form input[name="name"]').fill('Poli Mata');
  await ui.locator('#add-tv-form button[type="submit"]').click();
  await ui.locator('[data-id="4"]').waitFor();
  assert.equal(await ui.locator('[data-id="1"] input[name="name"]').inputValue(), 'Unsaved edit');
  assert.equal(await ui.locator('[data-id="4"] input[name="name"]').inputValue(), 'Poli Mata');
  assert.equal(await ui.locator('[data-id="4"] select[name="resolution"]').inputValue(), '1080p');
  assert.equal(await ui.locator('.count-label').textContent(), '4');
  assert.equal(await ui.locator('#connected-count').textContent(), '0 of 4 TVs connected');
  await mkdir('test-results', { recursive: true });
  await ui.screenshot({ path: 'test-results/add-tv-desktop.png', fullPage: true });
  for (let id = 5; id <= 10; id += 1) await api('devices', { name: `Poli ${id}` });
  await until(async () => await ui.locator('.display-card').count() === 10, 'cards from another admin client');
  assert.equal(await ui.locator('[data-id="1"] input[name="name"]').inputValue(), 'Unsaved edit');
  await ui.locator('#demo-button').click();
  await until(() => app.store.device('10').url.endsWith('/demo/queue/10'), 'dynamic demo configuration');
  await api('browser/login');
  await app.manager.loginPage.getByRole('button', { name: 'Sign in to demo' }).click();
  await app.manager.loginPage.waitForURL('**/demo/queue/1');
  for (const id of ['1', '4', '10']) await api(`devices/${id}/start`);
  await until(() => ['1', '4', '10'].every(id => app.manager.snapshot(id).frameAvailable), 'added displays share the login');
  const firstPage = app.manager.displays.get('1').page;
  const fourthPage = app.manager.displays.get('4').page;
  assert.equal(await app.manager.displays.get('10').page.locator('h1').textContent(), 'Queue 10');
  await api('devices/10/configure', { ...app.store.device('10'), readySelector: '' });
  await ui.locator('[data-id="10"] [data-action="approve"]').click();
  await until(() => app.manager.snapshot('10').frameAvailable, 'manual approval on TV 10');
  const tenthPage = app.manager.displays.get('10').page;
  const receiver = await browser.newPage();
  receiver.on('pageerror', error => pageErrors.push(error.message));
  await receiver.goto(`${base}/tv/10/`);
  await receiver.locator('#display').waitFor({ state: 'visible' });
  assert.match(await receiver.locator('#receiver-id').textContent(), /^TV 10 /);
  assert.equal(await receiver.locator('#tv-name').textContent(), 'Poli 10');
  assert.match(await receiver.locator('#display').getAttribute('src'), /\/api\/tv\/10\/frame.jpg/);
  const reload = receiver.waitForEvent('load');
  await api('devices/10/reconnect');
  await reload;
  await receiver.locator('#display').waitFor({ state: 'visible' });
  for (const [id, sinkId] of [['4', 'aqua-2'], ['10', 'aqua-1']]) {
    await api(`devices/${id}/cast-discover`);
    await api(`devices/${id}/cast-assign`, { sinkId });
    await api(`devices/${id}/cast-start`);
  }
  await ui.locator('[data-id="10"] summary').click();
  await ui.locator('[data-id="10"] [data-action="remove"]').click();
  await ui.locator('#cancel-remove-tv').click();
  assert.equal(app.store.device('10').enabled, true, 'cancel leaves the TV running');
  await ui.locator('[data-id="10"] [data-action="remove"]').click();
  await ui.locator('#confirm-remove-tv').click();
  await ui.locator('[data-id="10"]').waitFor({ state: 'detached' });
  assert.equal(tenthPage.isClosed(), true);
  assert.equal(driver.launches.find(item => item.id === '10').page.isClosed(), true);
  assert.equal(app.manager.displays.has('10'), false);
  assert.equal(app.caster.entries.has('10'), false);
  assert.equal(app.caster.snapshot('4').state, 'casting');
  assert.equal(app.manager.displays.get('1').page, firstPage);
  assert.equal(app.manager.displays.get('4').page, fourthPage);
  assert.equal(app.manager.snapshot('4').frameAvailable, true);
  await receiver.locator('#display').waitFor({ state: 'hidden' });
  assert.equal((await fetch(`${base}/tv/10`)).status, 404);
  await app.close();
  app = await createApplication(options);
  await app.listen(port, '127.0.0.1');
  token = (await (await fetch(`${base}/api/admin/session`)).json()).token;
  await app.manager.restore();
  await until(() => app.manager.snapshot('4').frameAvailable, 'added display survives service restart');
  assert.equal(app.store.device('4').name, 'Poli Mata');
  assert.equal(app.store.device('4').castSink.id, 'aqua-2');
  assert.equal(app.store.value.devices.some(device => device.id === '10'), false);
  await until(async () => await ui.locator('[data-id="4"] [data-action="preview"]').isEnabled(), 'preview after restart');
  await ui.locator('[data-id="4"] [data-action="preview"]').click();
  await api('devices/4/remove');
  await until(async () => !(await ui.locator('#preview-dialog').evaluate(dialog => dialog.open)), 'removing from another client closes the preview');
  for (const device of [...app.store.value.devices]) await api(`devices/${device.id}/remove`);
  await ui.locator('#empty-displays').waitFor({ state: 'visible' });
  assert.equal(await ui.locator('.display-card').count(), 0);
  assert.equal(await ui.locator('#cast-all').isDisabled(), true);
  assert.equal(await ui.locator('#discover-tvs').isDisabled(), true);
  assert.equal(await ui.locator('#connected-count').textContent(), '0 of 0 TVs connected');
  await ui.setViewportSize({ width: 390, height: 844 });
  await ui.locator('#add-tv').click();
  await ui.locator('#add-tv-form input[name="name"]').fill('New mobile TV');
  await ui.screenshot({ path: 'test-results/add-tv-mobile.png', fullPage: true });
  assert.equal(await ui.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'mobile dialog does not overflow');
  await ui.locator('#add-tv-form button[type="submit"]').click();
  await ui.locator('[data-id="11"]').waitFor();
  assert.equal(await ui.locator('#empty-displays').isVisible(), false);
  assert.equal(await ui.locator('#connected-count').textContent(), '0 of 1 TVs connected');
  assert.equal(await ui.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'dynamic mobile cards do not overflow');
  assert.deepEqual(pageErrors, []);
});
